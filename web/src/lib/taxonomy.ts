export interface SchoolRecord {
  name: string;
  subOffice: string;
}

/** Flat list of all schools with their sub-office, generated from SCHOOL_MAP. */
export const SCHOOLS: SchoolRecord[] = Object.entries(SCHOOL_MAP).flatMap(([subOffice, schools]) =>
  schools.map((name) => ({ name, subOffice })),
);

/** Deduplicated, sorted list of all school names. */
export const SCHOOL_NAMES: string[] = Array.from(new Set(SCHOOLS.map((s) => s.name))).sort((a, b) =>
  a.localeCompare(b),
);

/** Return the sub-office for a given school name. */
export function subOfficeFor(school: string): string {
  const record = SCHOOLS.find((s) => s.name === school);
  return record?.subOffice ?? SUB_OFFICE_NAMES[0];
}

/** Backward-compatible alias — district is the sub-office in the new model. */
export function districtFor(school: string): string {
  return subOfficeFor(school);
}

/** Schools belonging to a given sub-office, sorted alphabetically. */
export function schoolsForSubOffice(subOffice: string): string[] {
  return (SCHOOL_MAP[subOffice] ?? []).slice().sort((a, b) => a.localeCompare(b));
}

