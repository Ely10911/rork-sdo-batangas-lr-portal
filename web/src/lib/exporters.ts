/** Report export helpers — CSV, Excel-compatible XLS and print-to-PDF. */

export interface ReportTable {
  title: string;
  subtitle: string;
  columns: string[];
  rows: (string | number)[][];
}

function download(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

function escapeCsv(value: string | number): string {
  const text = String(value ?? "");
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

export function exportCsv(table: ReportTable, filename: string): void {
  const lines = [
    `# ${table.title}`,
    `# ${table.subtitle}`,
    table.columns.map(escapeCsv).join(","),
    ...table.rows.map((row) => row.map(escapeCsv).join(",")),
  ];
  download(new Blob([lines.join("\n")], { type: "text/csv;charset=utf-8;" }), `${filename}.csv`);
}

export function exportExcel(table: ReportTable, filename: string): void {
  const head = table.columns.map((c) => `<th style="background:#C42B2B;color:#FFFFFF;text-align:left">${c}</th>`).join("");
  const body = table.rows
    .map((row) => `<tr>${row.map((cell) => `<td>${String(cell ?? "")}</td>`).join("")}</tr>`)
    .join("");
  const html = `<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel"><head><meta charset="utf-8" /></head><body>
    <h3>${table.title}</h3><p>${table.subtitle}</p>
    <table border="1" cellspacing="0" cellpadding="6"><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>
  </body></html>`;
  download(new Blob([html], { type: "application/vnd.ms-excel;charset=utf-8;" }), `${filename}.xls`);
}

export function exportPdf(table: ReportTable): void {
  const win = window.open("", "_blank", "width=1024,height=768");
  if (!win) {
    console.warn("LRMS: PDF export blocked by the browser pop-up settings.");
    return;
  }
  const head = table.columns.map((c) => `<th>${c}</th>`).join("");
  const body = table.rows.map((row) => `<tr>${row.map((cell) => `<td>${String(cell ?? "")}</td>`).join("")}</tr>`).join("");
  win.document.write(`<!doctype html><html><head><title>${table.title}</title>
  <style>
    @page { size: A4; margin: 16mm; }
    body { font-family: "Public Sans", Helvetica, Arial, sans-serif; color:#1a1a2e; }
    header { border-bottom: 2px solid #C42B2B; padding-bottom: 10px; margin-bottom: 18px; }
    .eyebrow { font-size: 10px; letter-spacing: .22em; text-transform: uppercase; color:#8a2a2a; }
    h1 { font-family: Georgia, serif; font-size: 22px; margin: 6px 0 2px; }
    p.sub { margin: 0; font-size: 12px; color:#4b5b66; }
    table { width: 100%; border-collapse: collapse; font-size: 11px; margin-top: 12px; }
    th { background: #C42B2B; color: #FFFFFF; text-align: left; padding: 7px 8px; }
    td { border-bottom: 1px solid #E2DACB; padding: 6px 8px; }
    tr:nth-child(even) td { background: #fdf2f2; }
    footer { margin-top: 20px; font-size: 10px; color:#8a2a2a; }
  </style></head><body>
    <header>
      <div class="eyebrow">Republic of the Philippines · Department of Education</div>
      <h1>${table.title}</h1>
      <p class="sub">${table.subtitle}</p>
    </header>
    <table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>
    <footer>Generated by the SDO Batangas Learning Resource Management System on ${new Date().toLocaleString("en-PH")}.</footer>
  </body></html>`);
  win.document.close();
  win.focus();
  setTimeout(() => win.print(), 400);
}
